// 元JSONを一切変更せず、file://でも使える静的JSバンドルを生成する。
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const root = path.join(__dirname, '..', 'data');
const read = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
const timetables = read('all_six_timetables.json');
const network = read('keio_all_data.json');
if (JSON.stringify(timetables.timetables) !== JSON.stringify(network.timetables)) throw Error('2ファイルの時刻表が一致しません');
const manifest = { version: 1, files: ['all_six_timetables.json', 'keio_all_data.json'].map(name => ({ name,
  sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join(root, name))).digest('hex') })),
  counts: Object.fromEntries(Object.entries(timetables.timetables).map(([key, table]) => [key, table.trains.length])) };
fs.writeFileSync(path.join(root, 'seed.js'), '// Generated by scripts/build-data.cjs. 元JSONはdataフォルダーに保持。\n' +
  'globalThis.RailwaySeed = ' + JSON.stringify({ timetables, network, manifest }).replace(/</g, '\\u003c') + ';\n');
fs.writeFileSync(path.join(root, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(manifest.counts);
